const codes = raw
  .trim()
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean);

const displayNames = new Intl.DisplayNames(["tr"], { type: "region" });

const pairs = codes.map((code) => {
  const name = displayNames.of(code);
  if (!name || name === code) {
    throw new Error(
      `Intl.DisplayNames tr için isim üretemedi: ${code} (Node/ICU sürümünü kontrol edin)`
    );
  }
  return { code, name };
});

const out = path.join(__dirname, "..", "src", "data", "iso3166-alpha2-countries.json");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(pairs, null, 2));
console.log("wrote", pairs.length, "countries to", out);
